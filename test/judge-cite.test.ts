import assert from "node:assert/strict";
import { after, describe, it } from "node:test";

import { toAbsolutePath } from "../src/core/brand.js";
import type { ExecRequest } from "../src/core/runtime.js";
import { checkCitations, citationsIn, citeVerifier } from "../src/judge/cite.js";
import type { Fetched, SourceFetcher } from "../src/judge/fetch.js";
import { perturb } from "../src/judge/probe.js";
import { parseRequest } from "../src/judge/request.js";
import { contentHash } from "../src/judge/span.js";
import { type JudgeDeps, runVerb } from "../src/judge/verbs.js";
import { DEFAULT_VERIFIERS } from "../src/judge/verify.js";
import { fmPaths } from "../src/task/paths.js";
import { type TempRepo, tempRepo, write } from "./git-support.js";
import { memoryFs } from "./memory-fs.js";
import { repoRuntime } from "./repo.js";
import { cliJson, execResult, fakeRuntime, field } from "./support.js";

const PAPER = [
  "<html><head><title>Fabrication and errors in the bibliographic citations generated by ChatGPT</title></head>",
  "<body><p>William H. Walters, Esther Isabelle Wilder. Scientific Reports, 2023.</p>",
  "<p>Of the 636 citations, 55% of the GPT-3.5 citations but just 18% of the GPT-4 citations are fabricated.</p>",
  "</body></html>",
].join("\n");

const DOI = "10.1038/s41598-023-41032-5";

const fetcher =
  (pages: Readonly<Record<string, Fetched>>): SourceFetcher =>
  (id) =>
    pages[id] ?? { status: "not-found" };

const deps = (pages: Readonly<Record<string, Fetched>>): JudgeDeps => {
  const fs = memoryFs({}, [toAbsolutePath("/home/ana/project/.finitemonkey")]);
  return {
    runtime: fakeRuntime({ fs }),
    paths: fmPaths(toAbsolutePath("/home/ana/project")),
    fetcher: fetcher(pages),
    verifiers: { ...DEFAULT_VERIFIERS, "source-span": citeVerifier, prose: citeVerifier },
  };
};

const call = (judge: JudgeDeps, record: Readonly<Record<string, unknown>>) => {
  const request = parseRequest(record);
  if (request === undefined) throw new Error(`bad request ${JSON.stringify(record)}`);
  return runVerb(judge, request);
};

const verifyText = (judge: JudgeDeps, text: string) => {
  const row = call(judge, { verb: "classify", file: "note.md", text }).result?.rows[0];
  return { row, verified: call(judge, { verb: "verify", claim: row?.claim }) };
};

const ok = (content: string): Fetched => ({ status: "ok", content });

const QUOTE = "55% of the GPT-3.5 citations but just 18% of the GPT-4 citations are fabricated";

describe("citations resolve and quoted spans match", () => {
  it("a real DOI with a matching quote is verified and records the span and the content hash", () => {
    const judge = deps({ [DOI]: ok(PAPER) });
    const { row, verified } = verifyText(
      judge,
      `In their audit, "${QUOTE}" ([Walters; Wilder 2023](https://doi.org/${DOI})).`,
    );
    assert.equal(row?.kind, "source-span");
    assert.equal(verified.claim?.state, "machine-verified");
    assert.equal(verified.claim.outcome, "verified");
    const support = call(judge, { verb: "export" }).export?.support.at(-1);
    assert.deepEqual(support?.anchors, [{ kind: "span", ref: DOI, span: QUOTE, hash: contentHash(PAPER) }]);
  });

  it("a fabricated DOI fails resolution and an altered author or year is a mismatch", () => {
    const judge = deps({ [DOI]: ok(PAPER) });
    assert.equal(checkCitations(`"${QUOTE}" (Walters 2023, 10.9999/made-up-2023)`, fetcher({})).outcome, "unresolved");
    const author = verifyText(judge, `"${QUOTE}" ([Johnson 2023](https://doi.org/${DOI})).`);
    assert.equal(author.verified.claim?.outcome, "mismatch");
    const year = verifyText(judge, `"${QUOTE}" ([Walters; Wilder 2021](https://doi.org/${DOI})).`);
    assert.equal(year.verified.claim?.outcome, "mismatch");
    assert.equal(year.verified.claim.state, "model-only");
  });

  it("an unreachable source is not verified, never false and never green", () => {
    const judge = deps({ [DOI]: { status: "unreachable", detail: "http 403" } });
    const { verified } = verifyText(judge, `"${QUOTE}" ([Walters; Wilder 2023](https://doi.org/${DOI})).`);
    assert.equal(verified.claim?.outcome, "not-verified");
    assert.equal(verified.claim.state, "model-only");
  });

  it("a lightly reworded quote is a mismatch; the same text without quotes stays non-literal", () => {
    const judge = deps({ [DOI]: ok(PAPER) });
    const reworded = QUOTE.replace("just 18%", "only 18%");
    const quoted = verifyText(judge, `"${reworded}" ([Walters; Wilder 2023](https://doi.org/${DOI})).`);
    assert.equal(quoted.verified.claim?.outcome, "mismatch");
    const plain = verifyText(
      judge,
      `Walters and Wilder found that most GPT citations are fabricated (https://doi.org/${DOI}).`,
    );
    assert.notEqual(plain.row?.kind, "source-span");
    assert.equal(plain.verified.claim?.outcome, "non-literal");
    assert.equal(plain.verified.claim.state, "model-only");
  });

  it("a one-word source mutant is caught", () => {
    const text = `"${QUOTE}" ([Walters; Wilder 2023](https://doi.org/${DOI})).`;
    assert.equal(checkCitations(text, fetcher({ [DOI]: ok(PAPER) })).outcome, "verified");
    const mutant = PAPER.replace(QUOTE, perturb(QUOTE));
    assert.notEqual(mutant, PAPER);
    assert.equal(checkCitations(text, fetcher({ [DOI]: ok(mutant) })).outcome, "mismatch");
    const twice = `${PAPER}\n<p>${QUOTE}</p>`;
    assert.equal(checkCitations(text, fetcher({ [DOI]: ok(twice) })).outcome, "verified-weak");
  });

  it("reads markdown links, bare DOIs and parenthesised labels", () => {
    assert.deepEqual(citationsIn(`see (Walters 2023, ${DOI}) and [a](https://example.org/x).`), [
      { id: "https://example.org/x", label: "a" },
      { id: DOI, label: "Walters 2023, " },
    ]);
  });
});

const repos: TempRepo[] = [];
after(() => {
  for (const repo of repos) repo.dispose();
});

describe("citation checks through the CLI", () => {
  it("runs offline against a fake fetch and sends only the cited identifier", async () => {
    const repo = tempRepo({ "note.md": `"${QUOTE}" ([Walters; Wilder 2023](https://doi.org/${DOI})).\n` });
    repos.push(repo);
    write(repo.root, ".finitemonkey/policy.yml", "guards:\n  judge-core: shadow\n");
    const sent: ExecRequest[] = [];
    const base = repoRuntime();
    const runtime = {
      ...base,
      exec: (request: ExecRequest) => {
        if (request.command !== "curl") return base.exec(request);
        sent.push(request);
        return execResult(0, `${PAPER}\n200`);
      },
    };
    const classified = await cliJson(["judge", "classify", "note.md"], { cwd: repo.root, runtime });
    const rows = field(classified.body, "data", "result", "rows");
    const claim = Array.isArray(rows) ? field(rows[0], "claim") : undefined;
    const verified = await cliJson(["judge", "verify", String(claim)], { cwd: repo.root, runtime });
    assert.equal(field(verified.body, "data", "claim", "state"), "machine-verified");
    assert.equal(sent.length, 1);
    const outgoing = JSON.stringify(sent);
    assert.ok(outgoing.includes(`https://doi.org/${DOI}`));
    assert.ok(!outgoing.includes("fabricated"));
    assert.ok(!outgoing.includes("Walters"));
  });
});
