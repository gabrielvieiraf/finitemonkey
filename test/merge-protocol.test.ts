import assert from "node:assert/strict";
import { describe, it } from "node:test";

import { git } from "./git-support.js";
import { hunksOf, merge, resultFile, ROUTES, sandbox, sides } from "./merge-support.js";
import { field } from "./support.js";

describe("merge protocol: git fault cases", () => {
  it("case 1: both sides add a route at the same point; C1 keeps both and the report traces the hunk", () => {
    const box = sandbox({ "src/routes.ts": ROUTES });
    try {
      sides(
        box,
        { "src/routes.ts": ROUTES.replace('"/home",', '"/home",\n  "/a",') },
        { "src/routes.ts": ROUTES.replace('"/home",', '"/home",\n  "/b",') },
      );
      const report = merge(box);
      assert.equal(report["outcome"], "merged", JSON.stringify(report["stops"]));
      assert.deepEqual(hunksOf(report, "src/routes.ts"), [{ cls: "C1", rule: "independent-additions" }]);
      const merged = resultFile(box, report, "src/routes.ts");
      assert.match(merged, /"\/a",\n {2}"\/b",/);
      const files = report["files"];
      assert.ok(Array.isArray(files));
      const hunk: unknown = field(files[0], "hunks");
      assert.ok(Array.isArray(hunk));
      assert.equal(field(hunk[0], "decision"), "kept both sides");
      assert.deepEqual(field(hunk[0], "trace", "base"), { start: 3, count: 0 });
      const commits = field(hunk[0], "trace", "theirsCommits");
      assert.ok(Array.isArray(commits) && commits.length === 1);
      assert.equal(git(box.root, "rev-parse", "main"), String(field(report, "target", "sha")));
    } finally {
      box.dispose();
    }
  });

  it("case 2: both sides add i18n keys to the same object; C5 keeps every key", () => {
    const base = '{\n  "app": {\n    "title": "Home"\n  }\n}\n';
    const box = sandbox({ "src/locales/en.json": base });
    try {
      sides(
        box,
        { "src/locales/en.json": base.replace('"Home"', '"Home",\n    "a": "A"') },
        { "src/locales/en.json": base.replace('"Home"', '"Home",\n    "b": "B"') },
      );
      const report = merge(box);
      assert.equal(report["outcome"], "merged", JSON.stringify(report["stops"]));
      assert.deepEqual(hunksOf(report, "src/locales/en.json"), [{ cls: "C5", rule: "merged-by-key" }]);
      assert.deepEqual(JSON.parse(resultFile(box, report, "src/locales/en.json")), {
        app: { title: "Home", a: "A", b: "B" },
      });
    } finally {
      box.dispose();
    }
  });

  it("case 3: a lockfile conflict is C4, regenerated by the declared generator and stable", () => {
    const generator =
      'import { readFileSync, writeFileSync } from "node:fs";\nconst deps = JSON.parse(readFileSync("package.json", "utf8")).dependencies;\nwriteFileSync("pnpm-lock.yaml", "lockfileVersion: 9\\n" + Object.keys(deps).sort().map((k) => k + ": " + deps[k]).join("\\n") + "\\n");\n';
    const pkg = (deps: string): string => `{\n  "name": "app",\n  "dependencies": {\n${deps}\n  }\n}\n`;
    const box = sandbox({
      "gen.mjs": generator,
      "package.json": pkg('    "base": "1.0.0"'),
      "pnpm-lock.yaml": "lockfileVersion: 9\nbase: 1.0.0\n",
      ".finitemonkey/config.yml": 'merge:\n  generators:\n    pnpm-lock.yaml: "node gen.mjs"\n',
    });
    try {
      sides(
        box,
        {
          "package.json": pkg('    "base": "1.0.0",\n    "a": "1.0.0"'),
          "pnpm-lock.yaml": "lockfileVersion: 9\na: 1.0.0\nbase: 1.0.0\n",
        },
        {
          "package.json": pkg('    "base": "1.0.0",\n    "b": "2.0.0"'),
          "pnpm-lock.yaml": "lockfileVersion: 9\nb: 2.0.0\nbase: 1.0.0\n",
        },
      );
      const report = merge(box);
      assert.equal(report["outcome"], "merged", JSON.stringify(report["stops"]));
      assert.deepEqual(hunksOf(report, "pnpm-lock.yaml"), [{ cls: "C4", rule: "regenerate" }]);
      assert.equal(resultFile(box, report, "pnpm-lock.yaml"), "lockfileVersion: 9\na: 1.0.0\nb: 2.0.0\nbase: 1.0.0");
    } finally {
      box.dispose();
    }
  });

  it("case 4: the same function changed on both sides is C7; it stops and nothing is committed", () => {
    const base = "export function total(a, b) {\n  return a + b;\n}\n";
    const box = sandbox({ "src/math.ts": base });
    try {
      sides(box, { "src/math.ts": base.replace("a + b", "a - b") }, { "src/math.ts": base.replace("a + b", "a * b") });
      const report = merge(box);
      assert.equal(report["outcome"], "stopped");
      assert.equal(report["commit"], null);
      assert.deepEqual(hunksOf(report, "src/math.ts"), [{ cls: "C7", rule: "same-lines-changed" }]);
      const path = String(field(report, "integration", "path"));
      assert.equal(git(path, "rev-parse", "HEAD"), String(field(report, "target", "sha")));
      assert.ok(git(path, "rev-parse", "MERGE_HEAD") !== "");
      assert.equal(git(box.root, "rev-parse", "main"), String(field(report, "target", "sha")));
    } finally {
      box.dispose();
    }
  });

  it("case 5: one side removes Jill, the other adds Jared next to her; Jill out, Jared in", () => {
    const box = sandbox({ "people.txt": "Ana\nJill\nZoe\n" });
    try {
      sides(box, { "people.txt": "Ana\nZoe\n" }, { "people.txt": "Ana\nJill\nJared\nZoe\n" });
      const report = merge(box);
      assert.equal(report["outcome"], "merged", JSON.stringify(report["stops"]));
      assert.equal(resultFile(box, report, "people.txt"), "Ana\nJared\nZoe");
    } finally {
      box.dispose();
    }
  });

  it("case 6: a rename on one side and a new call by the old name on the other merge clean, and callers stops", () => {
    const cart = "export function total(items) {\n  return items.length;\n}\n";
    const box = sandbox({
      "src/cart.js": cart,
      "src/app.js": 'import { total } from "./cart.js";\n\nexport const run = () => total([]);\n',
    });
    try {
      sides(
        box,
        {
          "src/cart.js": cart.replace("total", "sum"),
          "src/app.js": 'import { sum } from "./cart.js";\n\nexport const run = () => sum([]);\n',
        },
        { "src/report.js": 'import { total } from "./cart.js";\n\nexport const report = () => total([1]);\n' },
      );
      const report = merge(box);
      assert.equal(report["outcome"], "stopped");
      const stops = JSON.stringify(report["stops"]);
      assert.match(stops, /callers/);
      assert.match(stops, /total/);
      assert.equal(report["commit"], null);
    } finally {
      box.dispose();
    }
  });

  it("case 7: new functions on both sides keep every closing brace", () => {
    const base = "export function a() {\n  return 0;\n}\n";
    const box = sandbox({ "src/fns.ts": base });
    try {
      sides(
        box,
        { "src/fns.ts": `${base}\nexport function b() {\n  return 1;\n}\n` },
        { "src/fns.ts": `${base}\nexport function c() {\n  return 2;\n}\n` },
      );
      const report = merge(box);
      assert.equal(report["outcome"], "merged", JSON.stringify(report["stops"]));
      const merged = resultFile(box, report, "src/fns.ts");
      assert.equal(merged.split("\n").filter((line) => line === "}").length, 3);
      assert.match(merged, /function b\(\) \{\n {2}return 1;\n\}/);
      assert.match(merged, /function c\(\) \{\n {2}return 2;\n\}/);
    } finally {
      box.dispose();
    }
  });

  it("case 8: one side only reformatted, the other changed logic; C3 keeps the logic", () => {
    const base = "export function f(a, b) { return a + b; }\n";
    const box = sandbox({ "src/f.ts": base });
    try {
      sides(
        box,
        { "src/f.ts": "export function f(a, b) {\n  return a + b;\n}\n" },
        { "src/f.ts": "export function f(a, b) { return a * b; }\n" },
      );
      const report = merge(box);
      assert.equal(report["outcome"], "merged", JSON.stringify(report["stops"]));
      assert.deepEqual(hunksOf(report, "src/f.ts"), [{ cls: "C3", rule: "ours-only-formatted" }]);
      assert.match(resultFile(box, report, "src/f.ts"), /a \* b/);
    } finally {
      box.dispose();
    }
  });
});
