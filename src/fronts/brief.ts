import { join } from "node:path";

import { type AbsolutePath, toAbsolutePath } from "../core/brand.js";
import { isRecord, parseJsonObject } from "../core/parsed.js";
import type { Runtime } from "../core/runtime.js";
import { defaultOn } from "../defaults/items.js";
import type { Front, FrontsState } from "./state.js";

export const BRIEFING_FILE = ".finitemonkey/briefing.md";
export const BRIEFING_MAX_LINES = 120;

const READING = ["AGENTS.md", "CLAUDE.md", "CONTRIBUTING.md", "docs/plan"] as const;
const BUILD_SCRIPTS = ["build", "typecheck", "lint"] as const;
const VERIFY_SCRIPTS = ["test", "check"] as const;

const exists = (runtime: Runtime, root: AbsolutePath, path: string): boolean =>
  runtime.stat(toAbsolutePath(join(root, path))) !== undefined;

const scripts = (runtime: Runtime, root: AbsolutePath): readonly string[] => {
  const text = runtime.readText(toAbsolutePath(join(root, "package.json")));
  const parsed = text.ok ? parseJsonObject(text.value) : undefined;
  const found = parsed?.ok === true ? parsed.value["scripts"] : undefined;
  return isRecord(found) ? Object.keys(found) : [];
};

const commandsFor = (available: readonly string[], wanted: readonly string[]): readonly string[] =>
  wanted.filter((name) => available.includes(name)).map((name) => `- \`npm run ${name}\``);

const rules = (runtime: Runtime, root: AbsolutePath): readonly string[] => [
  "- Work only inside your front's worktree and branch; commit there.",
  "- Touch only the paths in your scope. Append-only registries get new lines, never removals or reordering.",
  "- New i18n keys go only under your namespace.",
  "- Never copy, move or redirect files into the main checkout; the scope guard blocks it.",
  "- A file outside git used by another front is locked; write a separate file and say so in the report.",
  "- Never resolve a conflict by picking a whole side; integration goes through `finitemonkey merge`.",
  ...(defaultOn(runtime, root, "no-attribution") ? ["- No AI attribution in commits or pull requests."] : []),
];

const reading = (runtime: Runtime, root: AbsolutePath): readonly string[] => [
  ...READING.filter((path) => exists(runtime, root, path)).map((path) => `- \`${path}\``),
  "- Your front block and contract, injected when you start.",
];

const verify = (runtime: Runtime, root: AbsolutePath, available: readonly string[]): readonly string[] => [
  ...commandsFor(available, VERIFY_SCRIPTS),
  "- `finitemonkey gate` before reporting; the report numbers must match its evidence.",
  ...(exists(runtime, root, ".finitemonkey/look.yml")
    ? ["- `finitemonkey look` on the screens you touched (1440 and 390 px)."]
    : []),
  "- Dev servers use your port range: `$FINITEMONKEY_PORT` (also `$PORT`).",
];

const REPORT = [
  "Write `.finitemonkey/reports/<front-id>.json` (`finitemonkey/front-report@1`) before you stop:",
  "`front`, `branch`, `head`, `commits`, `delivered`, `endpoints`, `tests` (`command`, `passed`, `failed`, `added`),",
  "`screenshots` (`path`, `viewport`, `opened`), `left_out` (`what`, `why`), `provisional_decisions`, `evidence`.",
  "Stopping early is fine: list what is missing in `left_out`.",
] as const;

const HUMAN = [
  "Product rules, prices, money, deleting data, public text, new dependencies and contracts outside your scope are",
  "decisions for the person. Make the smallest reversible choice, record it in `provisional_decisions` with",
  "`needs_human: true`, and keep going.",
] as const;

export const frontPrompt = (front: Pick<Front, "id" | "goal" | "paths">): string =>
  [`Read ${BRIEFING_FILE}.`, `Front: ${front.id}`, `Goal: ${front.goal}`, `Scope: ${front.paths.join(", ")}`].join(
    "\n",
  );

export const renderBriefing = (runtime: Runtime, root: AbsolutePath, state: FrontsState): string => {
  const available = scripts(runtime, root);
  const build = commandsFor(available, BUILD_SCRIPTS);
  return [
    "# Briefing",
    "",
    `Wave ${String(state.wave)} from ${state.base === "" ? "the current branch" : state.base}. Generated by \`finitemonkey brief\`; do not edit by hand.`,
    "",
    "## Rules",
    ...rules(runtime, root),
    "",
    "## Required reading",
    ...reading(runtime, root),
    "",
    "## How to build",
    ...(build.length === 0 ? ["- See the project README."] : build),
    "",
    "## How to verify",
    ...verify(runtime, root, available),
    "",
    "## Report",
    ...REPORT,
    "",
    "## Human decisions",
    ...HUMAN,
    "",
  ].join("\n");
};

export const briefingPath = (root: AbsolutePath): AbsolutePath => toAbsolutePath(join(root, BRIEFING_FILE));

export const lineCount = (text: string): number =>
  text.split("\n").filter((line, index, all) => index < all.length - 1 || line !== "").length;
