const handlerLine = (endpoint: Endpoint): readonly string[] => {
  const method = endpoint.method.toLowerCase();
  const single = `  http.${method}(${JSON.stringify(endpoint.path)}, ({ request, params }) => respond(${JSON.stringify(endpoint.id)}, request, params)),`;
  if (single.length <= 80) return [single];
  return [
    `  http.${method}(${JSON.stringify(endpoint.path)}, ({ request, params }) =>`,
    `    respond(${JSON.stringify(endpoint.id)}, request, params),`,
    "  ),",
  ];
};

export const domainName = (domain: string): string =>
  domain.replace(/-([a-z0-9])/g, (_match: string, letter: string) => letter.toUpperCase());

export const domainsOf = (registry: ApiRegistry): readonly string[] =>
  [...new Set(registry.endpoints.map((endpoint) => endpoint.domain))].sort();

export const domainHandlersFile = (registry: ApiRegistry, domain: string): string =>
  [
    imported("{ http }", "msw"),
    "",
    imported("{ respond }", "../respond"),
    "",
    `export const ${domainName(domain)}Handlers = [`,
    ...registry.endpoints.filter((endpoint) => endpoint.domain === domain).flatMap(handlerLine),
    "];",
    "",
  ].join("\n");

export const handlersIndexFile = (registry: ApiRegistry): string => {
  const domains = domainsOf(registry);
  return [
    ...domains.map((domain) => imported(`{ ${domainName(domain)}Handlers }`, `./${domain}`)),
    "",
    `export const handlers = [${domains.map((domain) => `...${domainName(domain)}Handlers`).join(", ")}];`,
    "",
  ].join("\n");
};

