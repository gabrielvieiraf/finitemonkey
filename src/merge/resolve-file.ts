import { basename } from "node:path";

import { matchesAny } from "../core/glob.js";
import { classifyHunk, type HunkVerdict, type MergeClass, type MergeSide } from "./hunk.js";
import type { MergeStop } from "./report.js";
import { isAppendOnly, isDeclaredGenerated, outOfScope, ownerOf, type Scopes } from "./scope.js";
import { type ConflictSegment, joinLines, parseSegments, type Segment } from "./segments.js";
import { isStructured, mergeJson } from "./structured.js";

export const LOCKFILES: ReadonlySet<string> = new Set([
  "package-lock.json",
  "npm-shrinkwrap.json",
  "pnpm-lock.yaml",
  "yarn.lock",
  "bun.lock",
  "Cargo.lock",
  "poetry.lock",
  "Pipfile.lock",
  "composer.lock",
  "Gemfile.lock",
  "go.sum",
  "uv.lock",
]);

const GENERATED_HEADER = /@generated|DO NOT EDIT|auto-generated|autogenerated/i;

export interface Stages {
  readonly path: string;
  readonly base: string | undefined;
  readonly ours: string | undefined;
  readonly theirs: string | undefined;
}

export interface FileInputs {
  readonly stages: Stages;
  readonly merged: string | undefined;
  readonly worktreeText: string | undefined;
  readonly linguistGenerated: boolean;
  readonly generator: string | undefined;
}

export const MERGE_HINTS = ["keep-both", "json-merge", "prefer-front", "stop"] as const;

export type MergeHint = (typeof MERGE_HINTS)[number];

export interface FileContext {
  readonly scopes: Scopes;
  readonly declaredRemovals: ReadonlySet<string>;
  readonly hints?: Readonly<Record<string, string>>;
}

export const hintFor = (context: FileContext, path: string): MergeHint | undefined => {
  const found = Object.entries(context.hints ?? {}).find(([pattern]) => matchesAny(path, [pattern]));
  return MERGE_HINTS.find((hint) => hint === found?.[1]);
};

export type FileAction =
  | { readonly kind: "write"; readonly text: string }
  | { readonly kind: "delete" }
  | { readonly kind: "take-ours-and-generate"; readonly command: string }
  | { readonly kind: "none" };

export interface ResolvedHunk {
  readonly segment: ConflictSegment;
  readonly verdict: HunkVerdict;
  readonly before: string | undefined;
}

export interface FileResolution {
  readonly path: string;
  readonly cls: MergeClass;
  readonly rule: string;
  readonly decision: string;
  readonly hunks: readonly ResolvedHunk[];
  readonly action: FileAction;
  readonly stop: MergeStop | undefined;
  readonly droppedSide: MergeSide | undefined;
  readonly sameIntent: readonly { readonly side: MergeSide; readonly text: string }[];
  readonly stages: Stages;
  readonly rerereProposal: boolean;
  readonly hint: MergeHint | null;
}

type Core = Omit<FileResolution, "stages" | "rerereProposal" | "hint">;

const fileLevel = (
  path: string,
  cls: MergeClass,
  rule: string,
  decision: string,
  action: FileAction,
  stop = false,
): Core => ({
  path,
  cls,
  rule,
  decision,
  hunks: [],
  action,
  stop: stop ? { reason: `${cls}:${rule}`, path } : undefined,
  droppedSide: undefined,
  sameIntent: [],
});

const isGenerated = (inputs: FileInputs, context: FileContext): boolean =>
  LOCKFILES.has(basename(inputs.stages.path)) ||
  inputs.linguistGenerated ||
  isDeclaredGenerated(context.scopes, inputs.stages.path) ||
  GENERATED_HEADER.test((inputs.stages.ours ?? "").split("\n").slice(0, 5).join("\n"));

const DECISIONS: Readonly<Record<MergeClass, string>> = {
  C0: "stopped: needs the owner of the file",
  C1: "kept both sides",
  C2: "kept one copy of the same text",
  C3: "kept the side that changed logic",
  C4: "took ours and regenerated",
  C5: "merged by key",
  C6: "stopped: one side removed what the other changed",
  C7: "stopped: needs a person",
  C8: "kept the owning side; the other side's change is already in it",
};

export const decisionOf = (verdict: HunkVerdict): string =>
  verdict.resolution === undefined
    ? DECISIONS[verdict.cls]
    : verdict.rule.startsWith("removal-declared")
      ? "kept the declared removal"
      : DECISIONS[verdict.cls];

const worst = (hunks: readonly ResolvedHunk[]): ResolvedHunk | undefined =>
  hunks.find((hunk) => hunk.verdict.resolution === undefined) ?? hunks[0];

const textOf = (segments: readonly Segment[], hunks: readonly ResolvedHunk[]): string => {
  let index = 0;
  const lines = segments.flatMap((segment) => {
    if (segment.kind === "clean") return segment.lines;
    const resolved = hunks[index]?.verdict.resolution ?? [];
    index += 1;
    return resolved;
  });
  return joinLines(lines);
};

const SAME_INTENT: Readonly<Record<string, MergeSide>> = {
  "same-text-after-format": "theirs",
  "ours-only-formatted": "ours",
  "theirs-only-formatted": "theirs",
};

const sameIntentLines = (hunk: ResolvedHunk): readonly { readonly side: MergeSide; readonly text: string }[] => {
  const side = SAME_INTENT[hunk.verdict.rule];
  if (side === undefined) return [];
  const kept = new Set(hunk.verdict.resolution ?? []);
  return hunk.segment[side].filter((line) => !kept.has(line)).map((text) => ({ side, text }));
};

const lineBased = (inputs: FileInputs, context: FileContext): Core => {
  const { path } = inputs.stages;
  const segments = parseSegments(inputs.merged ?? "");
  const hunkContext = {
    appendOnly: isAppendOnly(context.scopes, path),
    owner: ownerOf(context.scopes, path) ?? (hintFor(context, path) === "prefer-front" ? "theirs" : undefined),
    declaredRemoval: context.declaredRemovals.has(path),
  };
  const hunks = segments.flatMap((segment, index): ResolvedHunk[] => {
    if (segment.kind !== "conflict") return [];
    const previous = segments[index - 1];
    const before = previous?.kind === "clean" ? previous.lines[previous.lines.length - 1] : undefined;
    return [{ segment, verdict: classifyHunk(segment, hunkContext), before }];
  });
  const blocking = hunks.find((hunk) => hunk.verdict.resolution === undefined);
  const head = worst(hunks);
  const removal = hunks.find((hunk) => hunk.verdict.rule.startsWith("removal-declared"))?.verdict.rule;
  return {
    path,
    cls: head?.verdict.cls ?? "C1",
    rule: head?.verdict.rule ?? "no-conflict-hunks",
    decision: blocking === undefined ? "resolved every hunk" : decisionOf(blocking.verdict),
    hunks,
    action: blocking === undefined ? { kind: "write", text: textOf(segments, hunks) } : { kind: "none" },
    stop: blocking === undefined ? undefined : { reason: `${blocking.verdict.cls}:${blocking.verdict.rule}`, path },
    droppedSide: removal === undefined ? undefined : removal.endsWith("ours") ? "theirs" : "ours",
    sameIntent: hunks.flatMap(sameIntentLines),
  };
};

const missingSide = (inputs: FileInputs, context: FileContext): Core => {
  const { path, ours } = inputs.stages;
  if (!context.declaredRemovals.has(path)) {
    return fileLevel(path, "C6", "removal-against-change", DECISIONS.C6, { kind: "none" }, true);
  }
  const removedByOurs = ours === undefined;
  return {
    ...fileLevel(path, "C6", "removal-declared", "kept the declared removal", { kind: "delete" }),
    droppedSide: removedByOurs ? "theirs" : "ours",
  };
};

const resolveCore = (inputs: FileInputs, context: FileContext): Core => {
  const { path, base, ours, theirs } = inputs.stages;
  if (outOfScope(context.scopes, path))
    return fileLevel(path, "C0", "outside-both-scopes", DECISIONS.C0, { kind: "none" }, true);
  if (ours === undefined || theirs === undefined) return missingSide(inputs, context);
  if (isGenerated(inputs, context)) {
    return inputs.generator === undefined
      ? fileLevel(
          path,
          "C4",
          "no-generator-declared",
          "stopped: declare a generator in merge.generators",
          { kind: "none" },
          true,
        )
      : fileLevel(path, "C4", "regenerate", DECISIONS.C4, {
          kind: "take-ours-and-generate",
          command: inputs.generator,
        });
  }
  if (base === undefined) return fileLevel(path, "C7", "both-created", DECISIONS.C7, { kind: "none" }, true);
  if (isStructured(path) || hintFor(context, path) === "json-merge") {
    const merged = mergeJson(base, ours, theirs);
    if (merged?.text !== undefined)
      return fileLevel(path, "C5", "merged-by-key", DECISIONS.C5, { kind: "write", text: merged.text });
    if (merged !== undefined) {
      const keys = merged.conflicts.map((item) => item.key).join(", ");
      return fileLevel(path, "C7", `same-key-different-values: ${keys}`, DECISIONS.C7, { kind: "none" }, true);
    }
  }
  return lineBased(inputs, context);
};

const REPLAYED = /^<{7} /m;

export const resolveFile = (inputs: FileInputs, context: FileContext): FileResolution => ({
  ...resolveCore(inputs, context),
  hint: hintFor(context, inputs.stages.path) ?? null,
  stages: inputs.stages,
  rerereProposal:
    inputs.stages.ours !== undefined &&
    inputs.stages.theirs !== undefined &&
    inputs.worktreeText !== undefined &&
    !REPLAYED.test(inputs.worktreeText),
});
