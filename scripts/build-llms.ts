const STAMP = /\n<!-- translation of (\S+) sha256:([0-9a-f]{12}) -->\n$/;

function isExternal(target: string): boolean {
  return /^(?:[a-z][a-z0-9+.-]*:|#|\/)/i.test(target);
}

function absolute(target: string, sourceDir: string, base: string): string {
  if (isExternal(target)) return target;
  const hashAt = target.indexOf("#");
  const path = hashAt < 0 ? target : target.slice(0, hashAt);
  const anchor = hashAt < 0 ? "" : target.slice(hashAt);
  return base + posix.normalize(posix.join(sourceDir, path)) + anchor;
}

function rewriteLinks(markdown: string, source: string): string {
  const sourceDir = posix.dirname(source);
  return markdown
    .replace(/\]\(([^)\s]+)\)/g, (_match, target: string) => `](${absolute(target, sourceDir, blobBase)})`)
    .replace(/\bsrc="([^"]+)"/g, (_match, target: string) => `src="${absolute(target, sourceDir, rawBase)}"`);
}

function readText(path: string): Outcome<string> {
  try {
    return { ok: true, value: readFileSync(join(root, path), "utf8").replace(/\r\n/g, "\n") };
  } catch (error) {
    return { ok: false, error: `${path}: ${error instanceof Error ? error.message : String(error)}` };
  }
}

function withoutStamp(text: string): string {
  return text.replace(STAMP, "\n");
}

function section(source: string, content: string): string {
  return `---\n\nSource: ${blobBase}${source}\n\n${rewriteLinks(withoutStamp(content).trim(), source)}`;
}

function build(edition: Edition, read: (path: string) => Outcome<string>): Outcome<string> {
  const parts: string[] = [[...edition.header, "", `Repository: ${repository}`].join("\n")];
  for (const source of edition.sources) {
    const content = read(source);
    if (!content.ok) return content;
    parts.push(section(source, content.value));
  }
  return { ok: true, value: `${parts.join("\n\n")}\n` };
}

function fingerprint(text: string): string {
  return createHash("sha256").update(text).digest("hex").slice(0, 12);
}

function stamped(translation: Translation): Outcome<{ readonly text: string; readonly current: string }> {
  const text = readText(translation.file);
  if (!text.ok) return text;
  const source = readText(translation.source);
  if (!source.ok) return source;
  return { ok: true, value: { text: text.value, current: fingerprint(source.value) } };
}

function staleness(translation: Translation): string | undefined {
  const read = stamped(translation);
  if (!read.ok) return read.error;
  const match = STAMP.exec(read.value.text);
  if (match === null) return `${translation.file} has no translation stamp`;
  if (match[1] !== translation.source || match[2] !== read.value.current) {
    return `${translation.file} was translated from an older ${translation.source}. Update the translation, then run \`npm run llms:stamp\`.`;
  }
  return undefined;
}

function stamp(translation: Translation): Outcome<string> {
  const read = stamped(translation);
  if (!read.ok) return read;
  const body = withoutStamp(read.value.text).replace(/\n*$/, "\n");
  writeFileSync(
    join(root, translation.file),
    `${body}\n<!-- translation of ${translation.source} sha256:${read.value.current} -->\n`,
  );
  return { ok: true, value: translation.file };
}

function stampAll(): number {
  for (const translation of translations) {
    const done = stamp(translation);
    if (!done.ok) {
      process.stderr.write(`build-llms: ${done.error}\n`);
      return 2;
    }
    process.stdout.write(`${done.value} stamped\n`);
  }
  return 0;
}

function run(mode: "write" | "check" | "stamp"): number {
  if (mode === "stamp") return stampAll();
  let failed = false;
  for (const edition of editions) {
    const fresh = build(edition, readText);
    if (!fresh.ok) {
      process.stderr.write(`build-llms: ${fresh.error}\n`);
      return 2;
    }
    if (mode === "write") {
      writeFileSync(join(root, edition.output), fresh.value);
      process.stdout.write(`${edition.output} written\n`);
      continue;
    }
    const committed = readText(edition.output);
    if (committed.ok && committed.value === fresh.value) {
      process.stdout.write(`${edition.output} is up to date\n`);
    } else {
      process.stderr.write(`${edition.output} is out of date with its sources. Run \`npm run llms\` and commit it.\n`);
      failed = true;
    }
  }
  if (mode === "check") {
    for (const translation of translations) {
      const problem = staleness(translation);
      if (problem !== undefined) {
        process.stderr.write(`${problem}\n`);
        failed = true;
      }
    }
  }
  return failed ? 1 : 0;
}

const mode = process.argv.includes("--check") ? "check" : process.argv.includes("--stamp") ? "stamp" : "write";
process.exitCode = run(mode);
