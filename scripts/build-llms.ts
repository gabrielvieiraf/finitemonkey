import { readFileSync, writeFileSync } from "node:fs";
import { join, posix } from "node:path";
import { fileURLToPath } from "node:url";

type Outcome<T> = { readonly ok: true; readonly value: T } | { readonly ok: false; readonly error: string };

const repository = "https://github.com/gabrielvieiraf/finitemonkey";
const blobBase = `${repository}/blob/main/`;
const rawBase = "https://raw.githubusercontent.com/gabrielvieiraf/finitemonkey/main/";
const sources = ["README.md", "docs/faq.md", "docs/compare.md", "docs/AGENT-SETUP.md"] as const;
const output = "llms-full.txt";
const root = fileURLToPath(new URL("..", import.meta.url));

const header = [
  "# Finite Monkey: full documentation",
  "",
  "> Generated by scripts/build-llms.ts from the English README, FAQ, comparison and agent setup runbook. Do not edit by hand: change the sources and run `npm run llms`.",
  "",
  `Repository: ${repository}`,
].join("\n");

function isExternal(target: string): boolean {
  return /^(?:[a-z][a-z0-9+.-]*:|#|\/)/i.test(target);
}

function absolute(target: string, sourceDir: string, base: string): string {
  if (isExternal(target)) return target;
  const hashAt = target.indexOf("#");
  const path = hashAt < 0 ? target : target.slice(0, hashAt);
  const anchor = hashAt < 0 ? "" : target.slice(hashAt);
  return base + posix.normalize(posix.join(sourceDir, path)) + anchor;
}

function rewriteLinks(markdown: string, source: string): string {
  const sourceDir = posix.dirname(source);
  return markdown
    .replace(/\]\(([^)\s]+)\)/g, (_match, target: string) => `](${absolute(target, sourceDir, blobBase)})`)
    .replace(/\bsrc="([^"]+)"/g, (_match, target: string) => `src="${absolute(target, sourceDir, rawBase)}"`);
}

function readText(path: string): Outcome<string> {
  try {
    return { ok: true, value: readFileSync(join(root, path), "utf8").replace(/\r\n/g, "\n") };
  } catch (error) {
    return { ok: false, error: `${path}: ${error instanceof Error ? error.message : String(error)}` };
  }
}

function section(source: string, content: string): string {
  return `---\n\nSource: ${blobBase}${source}\n\n${rewriteLinks(content.trim(), source)}`;
}

function build(read: (path: string) => Outcome<string>): Outcome<string> {
  const parts: string[] = [header];
  for (const source of sources) {
    const content = read(source);
    if (!content.ok) return content;
    parts.push(section(source, content.value));
  }
  return { ok: true, value: `${parts.join("\n\n")}\n` };
}

function run(check: boolean): number {
  const fresh = build(readText);
  if (!fresh.ok) {
    process.stderr.write(`build-llms: ${fresh.error}\n`);
    return 2;
  }
  if (!check) {
    writeFileSync(join(root, output), fresh.value);
    process.stdout.write(`${output} written\n`);
    return 0;
  }
  const committed = readText(output);
  if (committed.ok && committed.value === fresh.value) {
    process.stdout.write(`${output} is up to date\n`);
    return 0;
  }
  process.stderr.write(`${output} is out of date with its sources. Run \`npm run llms\` and commit it.\n`);
  return 1;
}

process.exitCode = run(process.argv.includes("--check"));
